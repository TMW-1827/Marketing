/**
 * Зображення, що живуть на Google Drive.
 *
 * Фото продукції й обладнання важать від сотень кілобайт до кількох
 * мегабайт — у бандл вони не поміщаються, тому портал показує їх прямо з
 * Drive. Це працює лише для файлів, відкритих «усім, хто має посилання»:
 * саме так вони й налаштовані.
 *
 * Адреси прев'ю, а не прямого завантаження: Drive віддає зменшену копію
 * потрібної ширини, тому сторінка не тягне мегабайтні оригінали.
 */

/**
 * Дві адреси того самого прев'ю. Google обслуговує їх різними сервісами, і
 * котрась із них періодично відповідає помилкою на масових запитах —
 * компонент пробує наступну, замість того щоб лишити порожнє місце.
 */
export function driveImageCandidates(id: string, width = 600): string[] {
  return [
    `https://drive.google.com/thumbnail?id=${id}&sz=w${width}`,
    `https://lh3.googleusercontent.com/d/${id}=w${width}`,
  ]
}

/** Сторінка файлу на Drive — для «відкрити оригінал». */
export function driveFile(id: string): string {
  return `https://drive.google.com/file/d/${id}/view`
}
